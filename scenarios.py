def validate() -> list[str]:
    """
    Check scenarios before the evaluation starts.
    """

    problems = []

    for i, scenario in enumerate(SCENARIOS, 1):
        name = scenario.get("name")

        if not name:
            problems.append(f"scenario {i} has no name")

        criterion = scenario.get("criterion")
        if criterion not in {1, 2, 3, 4, 5}:
            problems.append(
                f"scenario {i} ('{name}') has an invalid criterion number"
            )

        texts = scenario.get("texts")
        bodies = scenario.get("bodies")
        appeals = scenario.get("appeals")

        kinds = sum(
            [
                bool(texts),
                bool(bodies),
                appeals is not None,
            ]
        )

        if kinds != 1:
            problems.append(
                f"scenario {i} ('{name}') must have exactly one of "
                f"'texts', 'bodies', or 'appeals'"
            )
            continue

        if texts:
            for j, text in enumerate(texts, 1):
                if not isinstance(text, str) or not text.strip():
                    problems.append(
                        f"scenario {i}, text {j} is empty or not a string"
                    )

                elif text.startswith("REPLACE ME"):
                    problems.append(
                        f"scenario {i} ('{name}'), text {j} is still "
                        f"the placeholder"
                    )

        if bodies:
            for j, body in enumerate(bodies, 1):
                if not isinstance(body, dict):
                    problems.append(
                        f"scenario {i}, body {j} is not a dict"
                    )

        if appeals is not None:
            if not isinstance(appeals, int) or appeals < 1:
                problems.append(
                    f"scenario {i} ('{name}') has an invalid appeals count"
                )

    return problems